/**
 * Who made the art this app ships, generated from `ASSETS.toml` — #358.
 *
 * ## Why this page exists, and why it is not a list somebody maintains
 *
 * [ADR 0023](../../../../docs/adr/0023-cc-by-assets-and-attribution.md) admits `CC-BY-4.0`
 * for a committed asset, and CC BY is the one licence in this repository whose
 * obligation never ends: it is discharged by the shipped application crediting
 * the work, every time it ships. §3(a)(2) lets that be satisfied *"in any
 * reasonable manner based on the medium"*, and the medium here is an APK —
 * somebody who installs this app never sees the repository, so a row in a file
 * in git is not reasonably discoverable *by them*. This screen is where the
 * notice is discoverable, beside the AGPL statement on the About page that is
 * there for the same reason.
 *
 * ⚠️ **It is derived, not written.** `ASSET001` already forces `ASSETS.toml` to
 * name every committed binary — a binary it does not name is a red build, and
 * discovery walks the tree rather than trusting an extension list. A screen
 * generated from the manifest inherits that completeness; a hand-maintained
 * list cannot, and ADR 0023 §"What would make this ADR wrong" says a
 * hand-maintained credits list should be read as the failure of that decision
 * rather than as a workaround.
 *
 * ## The sections, and the one that must not imply an obligation
 *
 * The first section is what the app **must** credit. The second — since
 * #597 — is work whose licence asks for no credit but does ask for a copy of
 * the licence to travel with it (Apache-2.0: the map's Roboto glyphs and the
 * pose model), and each copy this app ships is shown in it (#1744). The third is offered
 * anyway, for assets whose licence asks for nothing. They are separate, and
 * the courtesy one says in words that nothing is owed, because #358's third
 * bullet is that the screen *"must not imply an obligation that does not
 * exist"* — and ⚠️ until #597 the courtesy sentence was said of the two
 * Apache-2.0 works too, which is the converse mistake: denying one that does.
 *
 * ## What is rendered when something is wrong
 *
 * A manifest line the client cannot read, and an attribution-requiring entry
 * with a key missing, are both **shown**. `ASSET006` and `ASSET005` already
 * make each a red build, so neither can reach a release — and the answer to
 * "what if one does" is a visible problem rather than a row quietly missing
 * from the page. A dropped row is an asset credited nowhere, which is the one
 * outcome ADR 0023 §Consequences calls a licensing defect.
 *
 * ## The software, since #664
 *
 * The art is not the only thing here somebody else made. The app ships forty
 * packages of other people's code and the APK fifty native libraries more,
 * each under a licence that asks for its notice to travel with copies, and
 * until #664 none did. The last section lists every one, generated by
 * `scripts/check-third-party-notices.mjs` from the installed tree, and shows
 * the document that reproduces every notice in full on this screen, read out
 * of this app's own files, so it opens offline and inside the APK. ⚠️ An
 * empty list is rendered as a problem rather than as nothing: the same reason
 * as the attribution section's fixture, applied to a list that cannot
 * legitimately be empty.
 *
 * ⚠️ **The document is shown here, not linked.** A `target="_blank"` link to
 * it opened over the app inside the Android shell and left the rider with no
 * way back — `credits/notices-document.ts` says why — so a disclosure reads it
 * into the page on demand instead. ⚠️ Since #1744 the same goes for the
 * licence texts the licence-copy section names (Apache-2.0, OFL-1.1): a
 * disclosure per licence, read through `credits/licence-documents.ts`.
 */

export interface CreditsViewProps {
  /**
   * The manifest to credit from. Defaults to the one built into this bundle.
   *
   * A prop only so that `CreditsView.test.tsx` can render a manifest carrying
   * a `CC-BY-4.0` asset. There is none in the tree — ADR 0023 D-7 makes this
   * screen the thing that lands before the first one — so without it every
   * assertion about the attributed half would pass over an empty list.
   */
  readonly manifest?: string;
  /**
   * The third-party notices' contents. Defaults to the ones built into this
   * bundle; a prop so `CreditsView.test.tsx` can render a fixture and prove
   * a named package reaches the screen, and a broken document says so.
   */
  readonly notices?: string;
  /**
   * Reads the whole notices document. Defaults to
   * `credits/notices-document.ts` §`loadNoticesDocument`; a prop so a test can
   * hand in a fixture document, or one that fails to load.
   */
  readonly noticesDocument?: () => Promise<string>;
  /**
   * Reads one shipped licence text. Defaults to
   * `credits/licence-documents.ts` §`loadShippedLicence`; a prop so a test can
   * hand in a fixture, or one that fails to load — #1744.
   */
  readonly licenceText?: (licence: string) => Promise<string>;
  /**
   * Works the build copies in rather than commits — #618. Defaults to
   * `credits.ts` §`COPIED_WORKS`; a prop so a fixture manifest can be rendered
   * with nothing beside it.
   */
  readonly copied?: readonly AssetEntry[];
}

/**
 * The sentence CC BY 4.0 §3(a)(1)(A)(ii) and (iii) ask for, once.
 *
 * ADR 0023 D-3: the copyright notice and the warranty disclaimer are the same
 * sentence for every attributed work, so they are the screen's own wording
 * rather than a per-asset key that could drift row by row.
 */
const NOTICE =
  'Each work below remains the copyright of its creator and is used under the licence named ' +
  'beside it. The material is provided as-is, without warranties of any kind.';

/** ESA WorldCover's licence (#1975), from the same table every CC BY credit here links through. */
const CC_BY_LICENCE_URL = licenceLink('CC-BY-4.0');

/** One work, its licence, what was changed, and the files taken from it. */
function Work({ work }: { readonly work: CreditedWork }): JSX.Element {
  const licence = licenceLink(work.licence);
  const original = externalLink(work.url);
  return (
    <li>
      <p>
        <strong>{work.creator === '' ? 'Creator not recorded' : work.creator}</strong>
        {original === undefined ? null : (
          <>
            {' — '}
            <a href={original} target="_blank" rel="noreferrer">
              the original
            </a>
          </>
        )}
        {', under '}
        {licence === undefined ? (
          work.licence
        ) : (
          <a href={licence} target="_blank" rel="noreferrer">
            {work.licence}
          </a>
        )}
        .
      </p>
      <p>{modificationNote(work)}</p>
      <ul>
        {work.files.map((file) => (
          <li key={file}>
            <code>{file}</code>
          </li>
        ))}
      </ul>
    </li>
  );
}

/** A list of works, keyed by the first file each one took. */
function WorkList({ works }: { readonly works: readonly CreditedWork[] }): JSX.Element {
  return (
    <ul>
      {works.map((work) => (
        <Work key={`${work.creator}${work.licence}${work.files[0] ?? ''}`} work={work} />
      ))}
    </ul>
  );
}

/**
 * What the modification note says.
 *
 * ⚠️ `"no"` is a recorded answer rather than an absent one — ADR 0023 D-3 —
 * so it is rendered as a statement rather than as silence. A work whose entry
 * records nothing at all says that too, because the alternative is the screen
 * claiming an asset is unmodified on no evidence.
 */
function modificationNote(work: CreditedWork): string {
  if (work.modified === undefined) {
    return 'Whether this app changed it is not recorded.';
  }
  return work.modified.trim().toLowerCase() === 'no'
    ? 'Used unmodified.'
    : `Modified by this app: ${work.modified}`;
}

/** One package, its version and the licence it declares. */
function SoftwareList({ items }: { readonly items: readonly IncludedSoftware[] }): JSX.Element {
  return (
    <ul>
      {items.map((item) => (
        <li key={`${item.name}@${item.version}`}>
          <code>{item.name}</code> {item.version}, under {item.licence}
        </li>
      ))}
    </ul>
  );
}

/** Where reading the whole document has got to. */
type DocumentState =
  | { readonly kind: 'hidden' }
  | { readonly kind: 'loading' }
  | { readonly kind: 'shown'; readonly text: string }
  | { readonly kind: 'failed' };

/** What a {@link ReadInPlace} disclosure says and marks its text with. */
interface ReadInPlaceProps {
  readonly load: () => Promise<string>;
  readonly summary: string;
  readonly reading: string;
  readonly failedLabel: string;
  readonly failed: string;
  /** A `data-*` attribute set on the shown text, for tests and the browser gate. */
  readonly marker: Readonly<Record<`data-${string}`, string>>;
}

/**
 * A document this app ships, read into the page when a rider opens it —
 * #664 for the notices, #1744 for the licence texts.
 *
 * A `<details>`, not a button: the notices are something to read, not
 * something a rider came to this screen to do, and #666's "first control
 * above the fold" counts a button at the foot of Credits as a control a
 * rider must scroll to, where a `<summary>` is where explanation goes
 * (`browser/reflow-harness.tsx` §`firstControl`). Read once: closing it and
 * opening it again does not read it a second time. A read that fails says
 * so, rather than leaving an open disclosure over nothing.
 */
function ReadInPlace({
  load,
  summary,
  reading,
  failedLabel,
  failed,
  marker,
}: ReadInPlaceProps): JSX.Element {
  const [state, setState] = useState<DocumentState>({ kind: 'hidden' });
  const read = useRef<string | undefined>(undefined);

  const toggled = (open: boolean): void => {
    if (!open) {
      setState({ kind: 'hidden' });
      return;
    }
    if (read.current !== undefined) {
      setState({ kind: 'shown', text: read.current });
      return;
    }
    setState({ kind: 'loading' });
    load().then(
      (text) => {
        read.current = text;
        setState((current) => (current.kind === 'loading' ? { kind: 'shown', text } : current));
      },
      () => {
        setState((current) => (current.kind === 'loading' ? { kind: 'failed' } : current));
      },
    );
  };

  return (
    <details
      className="oyl-notices-more"
      onToggle={(event) => {
        toggled(event.currentTarget.open);
      }}
    >
      <summary>{summary}</summary>
      {state.kind === 'loading' ? (
        <StatusMessage tone="info" label="Opening" live>
          {reading}
        </StatusMessage>
      ) : null}
      {state.kind === 'failed' ? (
        <StatusMessage tone="warning" label={failedLabel} live>
          {failed}
        </StatusMessage>
      ) : null}
      {state.kind === 'shown' ? (
        <pre className="oyl-notices" {...marker}>
          {state.text}
        </pre>
      ) : null}
    </details>
  );
}

/**
 * The licence texts the licence-copy section's works ask to travel with them,
 * one disclosure each, in place of the `target="_blank"` link that left the
 * app inside the Android shell — #1744.
 */
function ShippedLicences({
  works,
  load,
}: {
  readonly works: readonly CreditedWork[];
  readonly load: (licence: string) => Promise<string>;
}): JSX.Element {
  const named = new Set(works.map((work) => work.licence));
  return (
    <>
      {READABLE_LICENCES.filter((licence) => named.has(licence)).map((licence) => (
        <ReadInPlace
          key={licence}
          load={() => load(licence)}
          summary={`Read the ${licence} licence`}
          reading={`Reading the ${licence} licence this app carries.`}
          failedLabel="Could not open the licence"
          failed={`The ${licence} licence this app carries could not be read just now.`}
          marker={{ 'data-licence-text': licence }}
        />
      ))}
    </>
  );
}

export function CreditsView({
  manifest,
  notices,
  noticesDocument = loadNoticesDocument,
  licenceText = loadShippedLicence,
  copied = COPIED_WORKS,
}: CreditsViewProps): JSX.Element {
  const credits = useMemo(
    () => creditsFrom(parseAssetManifest(manifest ?? ASSET_MANIFEST_SOURCE), copied),
    [manifest, copied],
  );
  const software = useMemo(() => parseNotices(notices ?? THIRD_PARTY_CONTENTS_SOURCE), [notices]);

  return (
    <>
      {credits.problems.length === 0 ? null : (
        <StatusMessage tone="warning" label="This page may be incomplete">
          <p>
            Some of what this app records about its assets could not be read, so somebody may be
            missing from this page.
          </p>
          <ul>
            {credits.problems.map((problem) => (
              <li key={problem}>{problem}</li>
            ))}
          </ul>
        </StatusMessage>
      )}

      <p>
        This page is generated from the record this app keeps of every file it ships that somebody
        else made — the artwork in the trainer game, the lettering on the map, the side
        camera&rsquo;s pose model, and the templates the Android build is assembled from. Nothing
        here is typed by hand, so an asset cannot be added without appearing here. The last section
        does the same for the software the app is built from. Links to the originals open in a new
        tab.
      </p>

      <div data-terms="attribution">
        <h2>Credited because the licence asks for it</h2>
        {credits.required.length === 0 ? (
          <StatusMessage tone="info" label="Nothing owed">
            No asset in this build is under a licence that requires attribution. Nothing below is
            credited because a licence asks for a credit; where a licence asks for something else,
            that is said beside it.
          </StatusMessage>
        ) : (
          <>
            <p>{NOTICE}</p>
            <WorkList works={credits.required} />
          </>
        )}
      </div>

      {credits.licenceCopy.length === 0 ? null : (
        <div data-terms="licence-copy">
          <h2>Shipped with a copy of its licence</h2>
          <p>
            Each of these is published under a licence that does not ask to be credited on a screen,
            but does ask that a copy of the licence travel with the work. That copy ships inside
            this app, and each licence named beside a work can be read in full below.
          </p>
          <WorkList works={credits.licenceCopy} />
          <ShippedLicences works={credits.licenceCopy} load={licenceText} />
        </div>
      )}

      <div data-terms="nothing">
        <h2>Credited as a courtesy</h2>
        {credits.courtesy.length === 0 ? (
          <p>
            {credits.licenceCopy.length === 0 && credits.unclassified.length === 0
              ? 'Nothing else in this build came from somebody outside this project.'
              : 'Nothing in this build is under a licence that asks for nothing at all.'}
          </p>
        ) : (
          <>
            <p>
              Each of these is published under a licence that asks for nothing in return — no credit
              is required and none is implied to be owed. They are here because the work was worth
              crediting anyway.
            </p>
            <WorkList works={credits.courtesy} />
          </>
        )}
      </div>

      {credits.unclassified.length === 0 ? null : (
        <div data-terms="unclassified">
          <h2>Credited under another licence</h2>
          <p>
            This page has not been told what these licences ask for, so it says nothing about it.
            The licence named beside each work is the one that applies.
          </p>
          <WorkList works={credits.unclassified} />
        </div>
      )}

      <h2>Where this list comes from</h2>
      <p>
        From <code>ASSETS.toml</code> in this project&rsquo;s own repository, which records the
        source, the licence and a checksum for every file of somebody else&rsquo;s that is committed
        to it. A file that is not recorded there fails the build, so this page is as complete as
        that record is.
      </p>

      {/*
        #1552, ADR 0054 D-3.6: the map data. Not a file this app ships, so not
        in `ASSETS.toml` and not generated from it: the maps are drawn
        from OpenStreetMap,
        and ODbL §4.3 asks for this notice wherever the result is shown. The
        ride screen and the map show `OSM_ATTRIBUTION` beside the work itself.
      */}
      <div data-terms="map-data">
        <h2>Map data</h2>
        <p>
          {OSM_ATTRIBUTION}. The maps in this app are drawn from OpenStreetMap, whose data is
          published under the{' '}
          <a href={ODBL_LICENCE_URL} target="_blank" rel="noreferrer">
            Open Database License 1.0
          </a>
          .
        </p>
        <p>{ODBL_NOTICE}</p>
        {/*
          #1975: the map archive also carries a land-cover layer derived from
          ESA WorldCover, which nothing here draws. CC BY 4.0 asks for the
          credit when the material is shared, and the owner ruled on
          2026-10-31 (#1557) that the app gives it.
        */}
        <p data-credit="worldcover">
          {WORLDCOVER_ATTRIBUTION}. The map files also hold a land-cover layer derived from ESA
          WorldCover, which is published under the{' '}
          <a href={CC_BY_LICENCE_URL} target="_blank" rel="noreferrer">
            Creative Commons Attribution 4.0 licence
          </a>
          . This app does not draw that layer.
        </p>
      </div>

      <div data-terms="software">
        <h2>Software this app includes</h2>
        <p>
          This app is built from open-source software written by other people, and each part is used
          under the licence named beside it. Every one of those licences asks for its notice to
          travel with the software, and the full third-party notices reproduce each one word for
          word. They ship inside this app, so they open here without a network.
        </p>
        <ReadInPlace
          load={noticesDocument}
          summary="Read the full notices"
          reading="Reading the notices this app carries."
          failedLabel="Could not open the notices"
          failed="The notices this app carries could not be read just now. The list below is still every package they cover."
          marker={{ 'data-notices-document': '' }}
        />
        {software.app.length === 0 || software.problems.length > 0 ? (
          <StatusMessage tone="warning" label="This list may be incomplete">
            <p>
              The list of software this app includes could not be read in full, so a package may be
              missing below. The full notices, above, are still complete.
            </p>
            {software.problems.length === 0 ? null : (
              <ul>
                {software.problems.map((problem) => (
                  <li key={problem}>{problem}</li>
                ))}
              </ul>
            )}
          </StatusMessage>
        ) : null}
        <h3>In the app</h3>
        <p>
          What a browser downloads when it opens this app. The Android app carries all of it too.
        </p>
        <SoftwareList items={software.app} />
        <h3>In the Android app only</h3>
        <p>
          The native libraries the Android app is built with, beside the app above. A browser never
          downloads these.
        </p>
        <SoftwareList items={software.android} />
        <p>
          Generated from this project&rsquo;s installed dependencies rather than typed by hand, and
          checked on every change: a package added without its notice fails the build.
        </p>
      </div>
    </>
  );
}
