/**
 * The realistic bicycle's four maps, drawn from arithmetic — #624.
 *
 * The bicycle under the realistic rider is this repository's own geometry
 * (`src/game/bicycle.ts`), drawn until #624 in three plain materials. What it
 * gains here is SURFACE, not triangles: a tyre's tread and sidewall and the
 * bar's tape as a normal map, the chainring's teeth with the chain on them and
 * the cassette on the rear hub as a normal map and a roughness map, and the
 * frame's clear coat as a roughness map alone. `src/game/bicycle-surfaces.ts`
 * says which part samples where; this file draws what is there.
 *
 * ## Why drawn, and drawn here
 *
 * - **Nothing is downloaded** (ADR 0026 D-4, ADR 0032 D-1), **nothing is
 *   generated by a model**, and **nothing is matched against another
 *   product's pictures** (ADR 0009): every texel is a function of the numbers
 *   below and of the part dimensions `bicycle.ts` already states — the same
 *   posture as `tools/icons/generate-icons.ts`, and dedicated `CC0-1.0` as
 *   those icons are (ADR 0024 D-5).
 * - **Heights in metres, normals from them.** Each band is a height field over
 *   the part's own surface — so many metres along, so many round — and a
 *   texel's normal is the field's slope in METRES per metre, taken at the
 *   part's real size. A 0.6 mm groove is 0.6 mm on the tyre it is drawn for,
 *   and nothing here is a "strength" somebody tuned by eye.
 * - **A pure function of its name.** {@link drawBicycleMap} reads no file, no
 *   clock and no random source; the noise the paint needs is an integer hash
 *   of the lattice point. So `ASSETS.toml`'s `inputsha256` for each map is the
 *   digest of these pixels ({@link pixelDigest}), and `provenance.test.ts`
 *   redraws every map in CI and compares — the decoded-pixel comparison
 *   `tools/icons/generate-icons.test.ts` makes, one step earlier: the pixels
 *   the encoder reads, rather than a PNG whose zlib bytes can drift.
 *
 * The KTX2 files the product loads are these pixels encoded by the pinned
 * `ktx` (`encode-ktx2.ts`), which `process-assets.ts --check` reproduces byte
 * for byte, as it does every other realistic file.
 */

